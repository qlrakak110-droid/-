#!/usr/bin/env python3
"""Builds the Roblox files for the Seoul skyline map from src/ (Rojo layout).

    python3 seoul-skyline/tools/build.py

  build/SeoulSkyline.rbxlx                       complete place: open in Studio -> Play (map builds) or bake via command bar
  build/SeoulSkyline_ServerStorage.rbxmx         -> drop into ServerStorage           (builder module tree)
  build/SeoulSkyline_ServerScriptService.rbxmx   -> drop into ServerScriptService     (SeoulSkylineBoot)
  build/SeoulSkyline_StarterPlayerScripts.rbxmx  -> drop into StarterPlayer.StarterPlayerScripts (client effects)
Layout rules (Rojo): folder with init.luau = ModuleScript (init.server.luau -> Script, init.client.luau -> LocalScript) whose
children are the other files; folder without init = Folder; x.luau = ModuleScript, x.server.luau = Script, x.client.luau = LocalScript.
"""
import os
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "build")
ref = [0]


def nid():
    ref[0] += 1
    return "RBX%032X" % ref[0]


def item(cls, name, source, children, props=""):
    out = ['<Item class="%s" referent="%s"><Properties><string name="Name">%s</string>' % (cls, nid(), escape(name))]
    if source is not None:
        src = source.replace("]]>", "]]]]><![CDATA[>")
        out.append('<ProtectedString name="Source"><![CDATA[%s]]></ProtectedString>' % src)
    out.append(props)
    out.append("</Properties>")
    out.extend(children)
    out.append("</Item>")
    return "".join(out)


def kind(fname):
    base = fname.rsplit(".", 1)[0]
    if base.endswith(".server"):
        return "Script", base[:-7]
    if base.endswith(".client"):
        return "LocalScript", base[:-7]
    return "ModuleScript", base


def walk(path):
    if os.path.isfile(path):
        c, n = kind(os.path.basename(path))
        return item(c, n, open(path, encoding="utf-8").read(), [])
    name = os.path.basename(path)
    cls, source, kids = "Folder", None, []
    for e in sorted(os.listdir(path)):
        p = os.path.join(path, e)
        if os.path.isdir(p):
            kids.append(walk(p))
            continue
        if not (e.endswith(".luau") or e.endswith(".lua")):
            continue
        c, n = kind(e)
        text = open(p, encoding="utf-8").read()
        if n == "init":
            cls, source = c, text
        else:
            kids.append(item(c, n, text, []))
    return item(cls, name, source, kids)


HEAD = '<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" version="4">'


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    p = os.path.join(OUT, name)
    with open(p, "w", encoding="utf-8") as f:
        f.write(HEAD + body + "</roblox>")
    print("seoul-skyline/build/" + name, os.path.getsize(p))


def color3(name, r, g, b):
    return '<Color3 name="%s"><R>%.6f</R><G>%.6f</G><B>%.6f</B></Color3>' % (name, r / 255, g / 255, b / 255)


def main():
    mod = os.path.join(SRC, "ServerStorage/SeoulSkyline")
    boot = os.path.join(SRC, "ServerScriptService/SeoulSkylineBoot.server.luau")
    client = os.path.join(SRC, "StarterPlayer/StarterPlayerScripts/SeoulSkylineClient")
    ref[0] = 0
    write("SeoulSkyline_ServerStorage.rbxmx", walk(mod))
    write("SeoulSkyline_ServerScriptService.rbxmx", walk(boot))
    if os.path.isdir(client):
        write("SeoulSkyline_StarterPlayerScripts.rbxmx", walk(client))
    # complete place (services + scripts + Future lighting). Terrain/parts are generated by SeoulSkylineBoot on Play,
    # or baked in edit mode with the command bar: require(game.ServerStorage.SeoulSkyline).Build()
    ref[0] = 100000
    lighting_props = (
        '<token name="Technology">4</token>'  # Enum.Technology.Future
        '<float name="ClockTime">18.2</float>'
        '<float name="GeographicLatitude">8</float>'
        '<float name="Brightness">2.4</float>'
        '<float name="ExposureCompensation">0.15</float>'
        + color3("Ambient", 38, 42, 58) + color3("OutdoorAmbient", 104, 100, 124)
        + '<bool name="GlobalShadows">true</bool>'
    )
    body = "".join([
        item("Workspace", "Workspace", None, [], '<float name="FallenPartsDestroyHeight">-500</float>'),
        item("Lighting", "Lighting", None, [], lighting_props),
        item("ServerStorage", "ServerStorage", None, [walk(mod)]),
        item("ServerScriptService", "ServerScriptService", None, [walk(boot)]),
        item("StarterPlayer", "StarterPlayer", None, [item("StarterPlayerScripts", "StarterPlayerScripts", None, [walk(client)] if os.path.isdir(client) else [])]),
    ])
    write("SeoulSkyline.rbxlx", body)


if __name__ == "__main__":
    sys.exit(main())
